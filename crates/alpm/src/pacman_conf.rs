//! Generate `pacman.conf` files for build roots and base images.

use std::fmt::Write;

#[derive(Debug, Clone)]
pub struct Repo {
    pub name: String,
    pub servers: Vec<String>,
    pub cache_servers: Vec<String>,
    pub sig_level: Option<String>,
}

#[derive(Debug, Clone)]
pub struct PacmanConf {
    pub arch: String,
    pub root_dir: Option<String>,
    pub db_path: Option<String>,
    pub cache_dirs: Vec<String>,
    pub sig_level: String,
    pub parallel_downloads: u32,
    pub repos: Vec<Repo>,
}

impl Default for PacmanConf {
    fn default() -> Self {
        PacmanConf {
            arch: "x86_64".into(),
            root_dir: None,
            db_path: None,
            cache_dirs: Vec::new(),
            sig_level: "Required DatabaseOptional".into(),
            parallel_downloads: 5,
            repos: Vec::new(),
        }
    }
}

impl PacmanConf {
    pub fn render(&self) -> String {
        let mut s = String::new();
        writeln!(s, "# generated by repoman; do not edit").unwrap();
        writeln!(s, "[options]").unwrap();
        if let Some(r) = &self.root_dir {
            writeln!(s, "RootDir = {r}").unwrap();
        }
        if let Some(d) = &self.db_path {
            writeln!(s, "DBPath = {d}").unwrap();
        }
        for c in &self.cache_dirs {
            writeln!(s, "CacheDir = {c}").unwrap();
        }
        writeln!(s, "HoldPkg = pacman glibc").unwrap();
        writeln!(s, "Architecture = {}", self.arch).unwrap();
        writeln!(s, "CheckSpace").unwrap();
        writeln!(s, "ParallelDownloads = {}", self.parallel_downloads).unwrap();
        writeln!(s, "SigLevel = {}", self.sig_level).unwrap();
        writeln!(s, "LocalFileSigLevel = Optional").unwrap();
        for r in &self.repos {
            writeln!(s).unwrap();
            writeln!(s, "[{}]", r.name).unwrap();
            if let Some(sl) = &r.sig_level {
                writeln!(s, "SigLevel = {sl}").unwrap();
            }
            for c in &r.cache_servers {
                writeln!(s, "CacheServer = {c}").unwrap();
            }
            for sv in &r.servers {
                writeln!(s, "Server = {sv}").unwrap();
            }
        }
        s
    }
}

/// Expand `$repo` and `$arch` in a Server template as pacman would.
pub fn expand_server(template: &str, repo: &str, arch: &str) -> String {
    template.replace("$repo", repo).replace("$arch", arch)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_repos_in_order() {
        let conf = PacmanConf {
            cache_dirs: vec!["/var/cache/pacman/pkg/".into()],
            repos: vec![
                Repo {
                    name: "repoman-staging".into(),
                    servers: vec!["http://coord:7800/staging/r1/stable/x86_64".into()],
                    cache_servers: vec![],
                    sig_level: Some("Never".into()),
                },
                Repo {
                    name: "core".into(),
                    servers: vec!["https://m/manjaro/stable/core/x86_64".into()],
                    cache_servers: vec!["http://coord:7800/cache".into()],
                    sig_level: None,
                },
            ],
            ..Default::default()
        };
        let text = conf.render();
        let staging = text.find("[repoman-staging]").unwrap();
        let core = text.find("[core]").unwrap();
        assert!(staging < core);
        assert!(text.contains("SigLevel = Never"));
        assert!(text.contains("CacheServer = http://coord:7800/cache\nServer = https://m/"));
        assert!(text.contains("Architecture = x86_64"));
    }

    #[test]
    fn expands_server_template() {
        assert_eq!(
            expand_server("https://m/manjaro/unstable/$repo/$arch", "extra", "x86_64"),
            "https://m/manjaro/unstable/extra/x86_64"
        );
    }
}
