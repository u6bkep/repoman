//! Base image construction with pacstrap, and the local image cache.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use repoman_common::config::WorkerConfig;
use repoman_common::proto::{Fd, ImageRef, JobResult};

use crate::exec::{JobCtx, run_logged};
use crate::sandbox::{RootSource, RunAs, Sandbox};
use crate::upload;

/// Directory holding the unpacked root of an image, if present.
pub fn image_root(scratch: &Path, sha256: &str) -> PathBuf {
    scratch.join("images").join(sha256).join("root")
}

/// Ensure an image is unpacked locally, downloading if needed.
pub async fn ensure_image(ctx: &JobCtx, image: &ImageRef) -> Result<PathBuf> {
    let root = image_root(&ctx.config.scratch_dir, &image.sha256);
    if root.join("usr").is_dir() && root.join(".repoman-complete").exists() {
        return Ok(root);
    }
    ctx.log(Fd::System, format!("fetching base image {}", &image.sha256[..12]));
    let tarball = ctx
        .config
        .scratch_dir
        .join("images")
        .join(format!("{}.tar.zst", image.sha256));
    upload::get_blob(&ctx.http, &image.url, &image.sha256, &tarball).await?;
    unpack_image(ctx, &tarball, &root).await?;
    let _ = tokio::fs::remove_file(&tarball).await;
    Ok(root)
}

async fn unpack_image(ctx: &JobCtx, tarball: &Path, root: &Path) -> Result<()> {
    let tmp = root.with_file_name("root.part");
    let _ = tokio::fs::remove_dir_all(&tmp).await;
    tokio::fs::create_dir_all(&tmp).await?;
    let mut cmd = tokio::process::Command::new("bsdtar");
    cmd.args(["--numeric-owner", "-xpf"])
        .arg(tarball)
        .arg("-C")
        .arg(&tmp)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .kill_on_drop(true);
    let (status, _tail) = run_logged(ctx, cmd, None).await?;
    if !status.success() {
        bail!("unpacking image failed: {status}");
    }
    tokio::fs::write(tmp.join(".repoman-complete"), b"").await?;
    tokio::fs::rename(&tmp, root).await?;
    Ok(())
}

/// Lines for `/etc/makepkg.conf.d/repoman.conf` inside images and roots.
pub fn makepkg_conf(build_uid: u32, extra: &str) -> String {
    let _ = build_uid;
    let mut s = String::from(
        "# generated by repoman\n\
         PKGDEST=/build/pkgdest\n\
         SRCDEST=/srcdest\n\
         SRCPKGDEST=/build/srcpkgdest\n\
         LOGDEST=/build/logs\n\
         BUILDDIR=/build/work\n\
         PACKAGER=\"repoman <repoman@localhost>\"\n\
         MAKEFLAGS=\"-j$(nproc)\"\n",
    );
    if !extra.trim().is_empty() {
        s.push_str(extra.trim_end());
        s.push('\n');
    }
    s
}

/// Build an image: pacstrap into a directory, populate keyrings, create the
/// build user, pack, hash, upload, and keep the unpacked tree locally.
pub async fn build_image(
    ctx: &JobCtx,
    stream: &str,
    pacman_conf: &str,
    packages: &[String],
    keyrings: &[String],
    makepkg_conf_extra: &str,
    upload_url: &str,
) -> Result<JobResult> {
    let cfg: &WorkerConfig = &ctx.config;
    let job_dir = ctx.job_dir();
    tokio::fs::create_dir_all(&job_dir).await?;
    let target = job_dir.join("root");
    tokio::fs::create_dir_all(&target).await?;
    let conf_path = job_dir.join("pacman.conf");
    // pacstrap runs the host pacman with this config; the CacheDir points at
    // the shared worker cache so downloads are reused by build roots.
    let cache_dir = cfg.scratch_dir.join("pkgcache");
    tokio::fs::create_dir_all(&cache_dir).await?;
    let mut conf_text = format!(
        "{pacman_conf}\n# host-side settings for pacstrap\n[options]\nCacheDir = {}\n",
        cache_dir.display()
    );
    if let Some(g) = &cfg.pacstrap_gpgdir {
        conf_text.push_str(&format!("GPGDir = {}\n", g.display()));
    }
    tokio::fs::write(&conf_path, conf_text).await?;

    ctx.stage("pacstrap");
    ctx.log(Fd::System, format!("pacstrap {} packages for {stream}", packages.len()));
    let mut cmd = tokio::process::Command::new("pacstrap");
    cmd.arg("-C")
        .arg(&conf_path)
        .args(["-G", "-M", "-K"])
        .arg(&target)
        .args(packages)
        .env("LANG", "C.UTF-8")
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .kill_on_drop(true);
    let (status, tail) = run_logged(ctx, cmd, None).await?;
    if !status.success() {
        bail!("pacstrap failed ({status}): {}", tail.join(" | "));
    }
    ctx.stage_done("pacstrap");

    ctx.stage("configure");
    // Keyrings and the build user, inside the new root.
    let sb = Sandbox {
        root: RootSource::Dir(target.clone()),
        mountpoint: job_dir.join("mnt"),
        binds: vec![],
        network: false,
        cgroup: ctx.cgroup_path(),
        hostname: "repoman-image".into(),
    };
    sb.prepare_dirs()?;
    let mut script = String::from("set -e\n");
    if !keyrings.is_empty() {
        script.push_str("pacman-key --init >/dev/null 2>&1 || true\n");
        script.push_str(&format!("pacman-key --populate {}\n", keyrings.join(" ")));
    }
    script.push_str(&format!(
        "groupadd -g {gid} builder 2>/dev/null || true\n\
         useradd -u {uid} -g {gid} -M -d /build -s /bin/bash builder 2>/dev/null || true\n\
         mkdir -p /build /srcdest /etc/makepkg.conf.d\n\
         chown {uid}:{gid} /build /srcdest\n\
         cat > /etc/makepkg.conf.d/repoman.conf <<'EOF'\n{conf}EOF\n\
         rm -f /etc/resolv.conf; : > /etc/resolv.conf\n\
         pacman -Q > /.repoman-packages\n",
        uid = cfg.build_uid,
        gid = cfg.build_uid,
        conf = makepkg_conf(cfg.build_uid, makepkg_conf_extra),
    ));
    let cmd = sb.command(&["/bin/sh".into(), "-c".into(), script], RunAs::Root, "/", &[])?;
    let (status, tail) = run_logged(ctx, cmd, None).await?;
    if !status.success() {
        bail!("image configuration failed ({status}): {}", tail.join(" | "));
    }
    let packages_installed: Vec<String> = tokio::fs::read_to_string(target.join(".repoman-packages"))
        .await
        .unwrap_or_default()
        .lines()
        .map(str::to_string)
        .collect();
    ctx.stage_done("configure");

    ctx.stage("pack");
    let tarball = job_dir.join("image.tar.zst");
    let script = format!(
        "set -o pipefail; bsdtar --numeric-owner --format=pax --acls --xattrs -cf - -C '{}' . | zstd -T0 -3 -q -o '{}'",
        target.display(),
        tarball.display()
    );
    let mut cmd = tokio::process::Command::new("bash");
    cmd.arg("-c")
        .arg(script)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .kill_on_drop(true);
    let (status, tail) = run_logged(ctx, cmd, None).await?;
    if !status.success() {
        bail!("packing image failed ({status}): {}", tail.join(" | "));
    }
    let (sha256, size) = upload::sha256_file(&tarball)?;
    let filename = format!("{stream}-{}.tar.zst", &sha256[..12]);
    ctx.log(Fd::System, format!("image {filename} is {} MiB", size / (1024 * 1024)));
    ctx.stage_done("pack");

    ctx.stage("upload");
    upload::put_blob(&ctx.http, upload_url, &cfg.token, &tarball, &sha256, &filename).await?;
    ctx.stage_done("upload");

    // Keep the unpacked tree as our local copy of the image.
    let final_root = image_root(&cfg.scratch_dir, &sha256);
    if let Some(p) = final_root.parent() {
        tokio::fs::create_dir_all(p).await?;
    }
    if !final_root.exists() {
        tokio::fs::write(target.join(".repoman-complete"), b"").await?;
        tokio::fs::rename(&target, &final_root)
            .await
            .with_context(|| format!("moving image into {}", final_root.display()))?;
    }
    let _ = tokio::fs::remove_file(&tarball).await;

    Ok(JobResult::Image {
        sha256,
        size,
        filename,
        packages: packages_installed,
    })
}
